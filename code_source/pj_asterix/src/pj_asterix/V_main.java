    private void bt_coActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bt_coActionPerformed
        String motPasse, login;

    motPasse = tx_mdp.getText();
    login = tx_login.getText();

    try {
        M_users utilConnecte = leControl.connection_Util(login, motPasse);
        if (utilConnecte == null) {
            lb_erreur.setText("erreur de connection");
        } else {
            this.utilisateurConnecte = utilConnecte;
            panel_co.setVisible(false);
            lb_util.setText("Bonjour " + utilConnecte.getName());

            lesAutorisations = leControl.autorisationRole(utilConnecte.getRoleId());

            for (Integer uneCle : lesAutorisations.keySet()){

                uneAutorisation = lesAutorisations.get(uneCle);

                unObjet = menuMap.get(uneAutorisation.getCode());

                // ✅ AJOUTER CETTE VÉRIFICATION ICI
                if (unObjet != null) {
                    classe = unObjet.getClass().toString();

                    switch(classe){
                        case "class javax.swing.JMenu" -> { 
                            mn = (JMenu) unObjet;
                            mn.setVisible(true);
                        }
                        case "class javax.swing.JMenuItem" -> { 
                            mi = (JMenuItem) unObjet;
                            mi.setVisible(true);
                        }
                    }
                } else {
                    // Debug : afficher le code non trouvé
                    System.out.println("Code non trouvé: " + uneAutorisation.getCode());
                }
            }
        }
    } catch (SQLException ex) {
        System.getLogger(V_main.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
    } catch (Exception ex) {
        System.getLogger(V_main.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
    }
    }//GEN-LAST:event_bt_coActionPerformed

