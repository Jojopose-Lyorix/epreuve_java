     private void scanMenus(JMenuBar menuBar) {

// Parcourir les éléments de la JMenuBar
        for (int i = 0; i < menuBar.getMenuCount(); i++) {
        mn = menuBar.getMenu(i);
        menuMap.put(mn.getName(), mn);
        if (!"mb_fichier".equals(mn.getName())){  // Vérifier que c'est bien "mb_fichier"
            mn.setVisible(false);
        }

        for (int j = 0; j < mn.getItemCount(); j++) {
            JMenuItem mi = mn.getItem(j);
            if (mi != null) {  // Ajouter cette vérification
                menuMap.put(mi.getName(), mi);
                if (!"mi_quit".equals(mi.getName())){  // Vérifier que c'est bien "mi_quit"
                    mi.setVisible(false);
                }
            }
        }
    }
    } 
