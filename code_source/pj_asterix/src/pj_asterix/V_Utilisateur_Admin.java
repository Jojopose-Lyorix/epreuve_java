public void afficher(C_asterix gestionUtilisateur, LinkedHashMap<Integer, M_users> lesUtilisateurs, LinkedHashMap<Integer, M_role> lesRoles) {
        this.lesUtilisateurs = lesUtilisateurs;
        this.lesRoles = lesRoles;
        this.controler = gestionUtilisateur;
        this.modeMonCompte = false;

        dm_tb_Util = (DefaultTableModel) table_util.getModel();
        dm_tb_Util.setRowCount(lesUtilisateurs.size());
        ligne = 0;

        for (Integer uneCle : lesUtilisateurs.keySet()) {
            unUtilisateur = lesUtilisateurs.get(uneCle);
            table_util.setValueAt(unUtilisateur.getId(), ligne, 0);
            table_util.setValueAt(unUtilisateur.getName(), ligne, 1);
            ligne++;
        }
        list_role.removeAllItems();
        for (Integer uneCle : lesRoles.keySet()) {
            unRole = lesRoles.get(uneCle);
            list_role.addItem(unRole.getCode());
            ligne++;
        }
        

        this.setSize(800, 350);
        this.setLocationRelativeTo(null);

        b_Modif.setVisible(true);
        b_Suppr.setVisible(true);
        b_Ajout.setVisible(true);
        
        setVisible(true);
    }

private void sePlacer() {
        iUser = table_util.getSelectedRow();

        id = (Integer) table_util.getValueAt(iUser, 0);

        tx_id.setEditable(false);
        tx_mdp.setEditable(true);
        unUtilisateur = lesUtilisateurs.get(id);
        tx_id.setText(String.valueOf(unUtilisateur.getId()));
        tx_name.setText(unUtilisateur.getName());
        tx_mail.setText(unUtilisateur.getEmail());
        
        tx_com.setText(unUtilisateur.getCommentaire());
        
         int roleId = unUtilisateur.getRoleId(); // ou getRole().getId() selon votre modèle
    M_role role = lesRoles.get(roleId);
    if (role != null) {
        list_role.setSelectedItem(role.getCode());
    }

    }
