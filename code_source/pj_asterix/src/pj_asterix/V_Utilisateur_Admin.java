    private void b_SupprActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_SupprActionPerformed
         if (table_util.getSelectedRow() == -1) {
        JOptionPane.showMessageDialog(this, 
            "Un utilisateur doit être sélectionné dans le tableau", 
            "Sélection obligatoire", 
            JOptionPane.ERROR_MESSAGE);
    } else {
        // Récupérer l'ID de l'utilisateur sélectionné
        int iUser = table_util.getSelectedRow();
        int idUtilisateur = (Integer) table_util.getValueAt(iUser, 0);
        String nomUtilisateur = (String) table_util.getValueAt(iUser, 1);
        
        // Demander confirmation
        int reponse = JOptionPane.showConfirmDialog(this,
            "Êtes-vous sûr de vouloir supprimer " + nomUtilisateur + " ?",
            "Attention !",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );
        
        if (reponse == JOptionPane.YES_OPTION) {
            controler.supprimerUtil(idUtilisateur);
        }
    }
    }//GEN-LAST:event_b_SupprActionPerformed

