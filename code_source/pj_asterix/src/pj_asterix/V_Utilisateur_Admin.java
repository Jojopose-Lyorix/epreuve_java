    private void bt_enregistrerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bt_enregistrerActionPerformed
       String vName = tx_name.getText();
    String vMail = tx_mail.getText();
    String vCom = tx_com.getText();
    
    String vRoleCode = (String) list_role.getSelectedItem();
    String vMdp = null;

if (!tx_mdp.getText().isEmpty()) {
    vMdp = BCrypt.withDefaults().hashToString(12, tx_mdp.getText().toCharArray());
}
    
    int vRoleId = -1;
    for (Integer key : lesRoles.keySet()) {
        if (lesRoles.get(key).getCode().equals(vRoleCode)) {
            vRoleId = key;
            break;
        }
    }

    int reponse = JOptionPane.showConfirmDialog(this,
        "Êtes-vous sûr de vouloir modifier " + tx_name.getText() + " ?",
        "Attention !",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.WARNING_MESSAGE
    );
         
    if (reponse == JOptionPane.YES_OPTION) {
        controler.modifierUtil(id, vName, vMail, vCom, vMdp, vRoleId);
        
        // ✅ AJOUTER : Fermer si mode "Mon Compte"
        if (modeMonCompte) {
            JOptionPane.showMessageDialog(this, "Modifications enregistrées !");
            this.dispose();
        }
    }
    }//GEN-LAST:event_bt_enregistrerActionPerformed

