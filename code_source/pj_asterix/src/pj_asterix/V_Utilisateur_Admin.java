    public void afficherMonCompte(C_asterix gestionUtilisateur, M_users utilisateur, LinkedHashMap<Integer, M_role> lesRoles) {
    this.lesRoles = lesRoles;
    this.controler = gestionUtilisateur;
    this.unUtilisateur = utilisateur;
    this.id = utilisateur.getId();
     this.modeMonCompte = true;
    
    // Créer un LinkedHashMap avec uniquement cet utilisateur
    this.lesUtilisateurs = new LinkedHashMap<>();
    this.lesUtilisateurs.put(utilisateur.getId(), utilisateur);

    // Remplir le tableau avec uniquement cet utilisateur
    dm_tb_Util = (DefaultTableModel) table_util.getModel();
    dm_tb_Util.setRowCount(1);
    table_util.setValueAt(utilisateur.getId(), 0, 0);
    table_util.setValueAt(utilisateur.getName(), 0, 1);
    
    // Remplir la liste des rôles
    list_role.removeAllItems();
    for (Integer uneCle : lesRoles.keySet()) {
        unRole = lesRoles.get(uneCle);
        list_role.addItem(unRole.getCode());
    }

    // Pré-remplir les champs avec les infos de l'utilisateur
    tx_id.setText(String.valueOf(utilisateur.getId()));
    tx_id.setEditable(false);
    tx_name.setText(utilisateur.getName());
    tx_mail.setText(utilisateur.getEmail());
    tx_mdp.setEditable(true);  // Ne pas permettre de modifier le mdp directement ici
    tx_com.setText(utilisateur.getCommentaire());
    
    // Sélectionner le rôle actuel
    int roleId = utilisateur.getRoleId();
    M_role role = lesRoles.get(roleId);
    if (role != null) {
        list_role.setSelectedItem(role.getCode());
    }
    // Désactiver la modification du rôle (l'utilisateur ne peut pas changer son propre rôle)
    list_role.setEnabled(false);

    this.setSize(760, 600);
    this.setLocationRelativeTo(null);

    // Cacher les boutons non nécessaires
    b_Modif.setVisible(false);
    b_Suppr.setVisible(false);
    b_Ajout.setVisible(false);
    
    // Cacher le tableau car on affiche directement les infos
    jScrollPane1.setVisible(false);
    
    setVisible(true);
}
